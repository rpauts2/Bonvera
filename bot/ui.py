def card(o, tiers, bank):
    reward_lines = []
    for x in tiers:
        reward_lines.append(f"• <b>{x.cashback} ₽</b>")
    reward_text = "\n".join(reward_lines) or "Уточняется у администратора"
    age_text = f"{o.age_min}+" if o.age_max >= 120 else f"{o.age_min}–{o.age_max} лет"
    s = (f"{bank.emoji} <b>{bank.name} · {o.name}</b>\n{'—'*22}\n"
         f"💵 <b>Твоё вознаграждение:</b>\n{reward_text}\n\n🎯 <b>Целевое действие:</b> {o.condition_text or o.action}\n"
         f"⏳ <b>Холд:</b> до {o.hold} дней после подтверждения сети\n🔞 <b>Возраст:</b> {age_text}\n")
    if o.verification_steps:
        s += "\n<b>Этапы выполнения:</b>\n" + "\n".join(f"{i+1}. {x}" for i, x in enumerate(o.verification_steps))
    if o.required_proofs:
        s += "\n\n<b>Какие подтверждения нужны:</b>\n" + "\n".join(f"• {x}" for x in o.required_proofs)
    s += "\n\n⚠️ На отдельных скриншотах ФИО нужно оставить видимым только там, где это прямо указано в чек-листе — для сверки владельца сделки. Всегда закрывай паспортные данные, дату рождения, адрес, телефон, полный номер карты/счёта, CVV/CVC, PIN, пароли, SMS-коды, QR-коды, лишний баланс и посторонние операции. Никогда не присылай фото карты целиком, паспорт или договор займа."
    if o.rules: s += f"\n🚫 Правила: {o.rules}\n"
    if o.forbidden: s += f"⚠️ Ограничения сети: {', '.join(o.forbidden)}\n"
    if bank.category == "mfo":
        i = o.mfo_info or {}
        if all(i.get(k) for k in ("psk", "rate", "term", "registry")):
            s += f"\n<b>Параметры кредитора:</b> ПСК {i['psk']} · ставка {i['rate']} · срок {i['term']} · реестр {i['registry']}"
        else:
            s += "\n<b>ПСК/ставка/срок:</b> в каталоге не подтверждены. Обязательно проверь полную стоимость займа, ставку, срок и сумму возврата в официальных документах кредитора до оформления."
        s += ("\n<b>Когда начисляется:</b> после фактической выдачи займа (если это целевое действие) и подтверждения партнёрской сетью, затем после холда.\n"
              "⚠️ Займ — это долг. Не оформляй его только ради вознаграждения; оцени полную стоимость и свои возможности возврата."
              " Досрочное погашение — по условиям договора и графику МФО.")
    elif bank.category == "cpl":
        s += "\n<b>Когда начисляется:</b> после принятия/валидации заявки партнёрской сетью. Сам займ оформлять не требуется, если этого прямо не указано в условии. Перед отправкой анкеты ознакомься с передачей данных партнёрам."
    elif bank.category == "bk":
        s += ("\n<b>Когда начисляется твой кэшбэк:</b> после выполнения партнёрского ЦД и подтверждения сети (postback), затем — после указанного холда."
              "\n🎁 <b>Бонус/фрибет самой БК:</b> это отдельная акция, не кэшбэк и не гарантированный доход.")
        if o.notes:
            s += "\n" + o.notes
        s += "\n⚠️ Депозит и ставки — только собственными средствами. Перед участием изучи правила букмекера и убедись, что акция доступна именно твоему аккаунту."
    else:
        s += "\n<b>Когда начисляется:</b> после подтверждения выпуска/активации и нужной операции банком или партнёрской сетью, затем — после холда. Покупку или платный выпуск оплачиваешь сам."
    if bank.category == "bk" and o.network_status != "approved":
        s += "\n\n⛔ <b>Оффер пока не согласован:</b> кэшбэк-формат должен быть письменно подтверждён менеджером."
    return s
