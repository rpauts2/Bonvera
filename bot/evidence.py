"""Offer-specific verification checklists; deliberately free of DB/framework imports."""


def verification(cat, condition, kind=""):
    if cat == "cards":
        steps = ["Открой персональную ссылку из заявки", "Получи карту / дождись доставки", "Активируй карту, если активация требуется"]
        low = (condition or "").lower()
        if any(x in low for x in ("покупк", "расход")):
            steps.append("Выполни требуемую покупку или расходную операцию в срок")
        if "оплачен" in low and "выпуск" in low:
            steps.append("Оплати выпуск зарубежной карты")
        return steps
    if cat == "bk":
        return ["Зарегистрируйся по персональной ссылке", "Пройди идентификацию у букмекера", "Внеси депозит только собственными средствами", "Выполни квалифицирующую ставку / ЦД из правил акции", "Дождись подтверждения партнёрской сети (postback)"]
    if cat == "mfo":
        return ["Перейди по персональной ссылке", "Заполни анкету и пройди проверку МФО", "Дождись фактической выдачи займа, если это ЦД оффера", "Дождись подтверждения партнёрской сети"]
    return ["Перейди по персональной ссылке", "Отправь заявку / выполни действие, указанное в карточке", "Дождись подтверждения валидности партнёрской сетью"]


def required_proofs(cat, condition, kind=""):
    """Minimal evidence set per conversion type; FIO is requested only where needed."""
    low = (condition or "").lower()
    if cat == "cards":
        out = [
            "Скрин личного кабинета банка/страницы карты: ФИО видно полностью для сверки, статус выпуска, доставки или активации карты. Спрячь паспортные данные, дату рождения, телефон, адрес, полный номер карты, баланс и коды."
        ]
        if any(x in low for x in ("покупк", "расход")):
            out.append(
                "Скрин истории операции: дата, сумма и название магазина/операции должны читаться. ФИО на этом скрине можно скрыть, если оно видно на первом; закрой полный номер карты, остаток, другие операции и реквизиты. Переводы, снятие наличных и возвраты не подходят, если иное письменно не согласовано."
            )
        if "оплачен" in low and "выпуск" in low:
            out.append(
                "Скрин оплаты выпуска карты: дата и сумма платежа должны быть видны. Закрой номер карты/счёта, телефон, баланс и прочие платежи."
            )
        return out
    if cat == "bk":
        return [
            "Скрин профиля букмекера: ФИО видно полностью для сверки, виден статус идентификации/верификации и дата регистрации. Закрой паспортные данные, дату рождения, телефон, адрес и большую часть номера счёта.",
            "Скрин истории пополнений: видны дата и сумма депозита(ов), чтобы можно было проверить минимальный депозит по офферу. Закрой платёжные реквизиты, номер карты и баланс.",
            "Скрин рассчитанной квалифицирующей ставки: событие, дата, сумма ставки, коэффициент и статус расчёта должны быть видны. Если бонус/фрибет является отдельным условием оффера, приложи также его начисление; не присылай пароли или данные карты."
        ]
    if cat == "mfo":
        return [
            "Скрин личного кабинета МФО с ФИО полностью для сверки и статусом заявки «Одобрено». Закрой паспортные данные, дату рождения, телефон, адрес, полный номер договора и реквизиты карты.",
            "Скрин фактической выдачи займа: статус «Займ выдан/Деньги перечислены», дата и сумма выдачи должны быть видны. Одного статуса «Одобрено» недостаточно для ЦД «выдача займа». Спрячь паспорт, номер договора, телефон, адрес, реквизиты карты и лишний баланс."
        ]
    return [
        "Скрин личного кабинета/заявки со статусом «Принята», «Верифицирована» или подтверждением привязки карты — в соответствии с условием оффера. Дата и название сервиса должны быть видны; ФИО оставь только если оно необходимо для сверки. Закрой паспортные данные, полный номер карты, телефон и коды подтверждения."
    ]
